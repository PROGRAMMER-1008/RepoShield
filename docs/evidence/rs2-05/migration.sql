BEGIN;

CREATE TABLE alembic_version (
    version_num VARCHAR(32) NOT NULL, 
    CONSTRAINT alembic_version_pkc PRIMARY KEY (version_num)
);

-- Running upgrade  -> 0001

CREATE TABLE repositories (
    id VARCHAR(64) NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    tenant_id VARCHAR(64) NOT NULL, 
    name TEXT NOT NULL, 
    path TEXT NOT NULL, 
    base_sha VARCHAR(40) NOT NULL, 
    policy_epoch INTEGER DEFAULT '1' NOT NULL, 
    PRIMARY KEY (id), 
    UNIQUE (tenant_id, name)
);

CREATE TABLE runs (
    id VARCHAR(64) NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    repository_id VARCHAR(64) NOT NULL, 
    input_digest VARCHAR(64) NOT NULL, 
    inputs JSONB NOT NULL, 
    PRIMARY KEY (id), 
    UNIQUE (repository_id, input_digest), 
    FOREIGN KEY(repository_id) REFERENCES repositories (id)
);

CREATE TABLE sessions (
    id VARCHAR(64) NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    repository_id VARCHAR(64) NOT NULL, 
    owner_id VARCHAR(64) NOT NULL, 
    state TEXT DEFAULT 'active' NOT NULL, 
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL, 
    revocation_epoch INTEGER DEFAULT '0' NOT NULL, 
    PRIMARY KEY (id), 
    CHECK (state IN ('active','revoked')), 
    FOREIGN KEY(repository_id) REFERENCES repositories (id)
);

CREATE TABLE attempts (
    id VARCHAR(64) NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    run_id VARCHAR(64) NOT NULL, 
    request_key VARCHAR(64) NOT NULL, 
    requested_by VARCHAR(64) NOT NULL, 
    state TEXT DEFAULT 'queued' NOT NULL, 
    finished_at TIMESTAMP WITH TIME ZONE, 
    result JSONB, 
    PRIMARY KEY (id), 
    CHECK (state IN ('queued','running','completed','failed-infrastructure','cancelled')), 
    UNIQUE (run_id, request_key), 
    FOREIGN KEY(run_id) REFERENCES runs (id)
);

CREATE TABLE action_requests (
    id VARCHAR(64) NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    session_id VARCHAR(64) NOT NULL, 
    action_digest VARCHAR(64) NOT NULL, 
    payload JSONB NOT NULL, 
    PRIMARY KEY (id), 
    FOREIGN KEY(session_id) REFERENCES sessions (id)
);

CREATE TABLE tasks (
    id VARCHAR(64) NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    attempt_id VARCHAR(64) NOT NULL, 
    stage TEXT NOT NULL, 
    state TEXT DEFAULT 'queued' NOT NULL, 
    tries INTEGER DEFAULT '0' NOT NULL, 
    max_tries INTEGER DEFAULT '3' NOT NULL, 
    available_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    lease_owner VARCHAR(64), 
    lease_epoch INTEGER DEFAULT '0' NOT NULL, 
    lease_until TIMESTAMP WITH TIME ZONE, 
    output JSONB, 
    error TEXT, 
    PRIMARY KEY (id), 
    CHECK (stage IN ('snapshot','analyze','tests','aggregate','publish')), 
    CHECK (state IN ('queued','running','succeeded','failed','cancelled')), 
    CHECK (tries >= 0 AND max_tries BETWEEN 1 AND 5 AND lease_epoch >= 0), 
    UNIQUE (attempt_id, stage), 
    FOREIGN KEY(attempt_id) REFERENCES attempts (id)
);

CREATE INDEX tasks_ready ON tasks (state, available_at);

CREATE TABLE decisions (
    id VARCHAR(64) NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    action_request_id VARCHAR(64) NOT NULL, 
    decision TEXT NOT NULL, 
    policy_digest VARCHAR(64) NOT NULL, 
    policy_epoch INTEGER NOT NULL, 
    expires_at TIMESTAMP WITH TIME ZONE, 
    nonce VARCHAR(64), 
    payload JSONB NOT NULL, 
    PRIMARY KEY (id), 
    CHECK (decision IN ('ALLOW','DENY','REVIEW_REQUIRED')), 
    FOREIGN KEY(action_request_id) REFERENCES action_requests (id), 
    UNIQUE (nonce)
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    attempt_id VARCHAR(64), 
    session_id VARCHAR(64), 
    actor_id VARCHAR(64) NOT NULL, 
    kind TEXT NOT NULL, 
    data JSONB NOT NULL, 
    PRIMARY KEY (id), 
    FOREIGN KEY(attempt_id) REFERENCES attempts (id), 
    FOREIGN KEY(session_id) REFERENCES sessions (id)
);

CREATE TABLE outbox (
    id VARCHAR(64) NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    attempt_id VARCHAR(64) NOT NULL, 
    kind TEXT NOT NULL, 
    payload JSONB NOT NULL, 
    state TEXT DEFAULT 'pending' NOT NULL, 
    tries INTEGER DEFAULT '0' NOT NULL, 
    available_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    PRIMARY KEY (id), 
    UNIQUE (attempt_id, kind), 
    CHECK (state IN ('pending','publishing','published','failed')), 
    FOREIGN KEY(attempt_id) REFERENCES attempts (id)
);

CREATE TABLE task_dependencies (
    task_id VARCHAR(64) NOT NULL, 
    depends_on VARCHAR(64) NOT NULL, 
    PRIMARY KEY (task_id, depends_on), 
    CHECK (task_id <> depends_on), 
    FOREIGN KEY(task_id) REFERENCES tasks (id), 
    FOREIGN KEY(depends_on) REFERENCES tasks (id)
);

CREATE TABLE executions (
    id VARCHAR(64) NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    decision_id VARCHAR(64) NOT NULL, 
    state TEXT NOT NULL, 
    outcome JSONB, 
    PRIMARY KEY (id), 
    CHECK (state IN ('queued','running','completed','failed-infrastructure','cancelled','unknown-outcome')), 
    UNIQUE (decision_id), 
    FOREIGN KEY(decision_id) REFERENCES decisions (id)
);

INSERT INTO alembic_version (version_num) VALUES ('0001') RETURNING alembic_version.version_num;

